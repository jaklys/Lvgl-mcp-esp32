#!/usr/bin/env node
/**
 * Generate src/resources/docs/widgets.generated.ts (the lvgl_docs
 * "widgets/<name>" pages) from LVGL's public widget headers: every
 * prototype with the first sentence of its doc comment, plus the enums.
 *
 * Usage: node scripts/gen-widget-table.mjs [<lvgl dir>]
 *   default <lvgl dir>: ../simulator/lib/lvgl (git checkout with submodules)
 * Re-run after an LVGL update and commit the result.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lvglDir = path.resolve(process.argv[2] ?? process.env.LVGL_DIR ?? path.join(packageDir, "..", "simulator", "lib", "lvgl"));
const inc = path.join(lvglDir, "include", "lvgl");
if (!existsSync(inc)) {
  console.error(`LVGL public headers not found in ${inc}`);
  process.exit(1);
}

/** Widgets enabled in simulator/lv_conf.h (name -> headers relative to include/lvgl). */
const WIDGETS = {
  obj: ["core/lv_obj.h", "core/lv_obj_pos.h"],
  animimg: ["widgets/lv_animimage.h"],
  arc: ["widgets/lv_arc.h"],
  bar: ["widgets/lv_bar.h"],
  barcode: ["widgets/lv_barcode.h"],
  button: ["widgets/lv_button.h"],
  buttonmatrix: ["widgets/lv_buttonmatrix.h"],
  calendar: ["widgets/lv_calendar.h", "widgets/lv_calendar_header_arrow.h", "widgets/lv_calendar_header_dropdown.h"],
  canvas: ["widgets/lv_canvas.h"],
  chart: ["widgets/lv_chart.h"],
  checkbox: ["widgets/lv_checkbox.h"],
  dropdown: ["widgets/lv_dropdown.h"],
  image: ["widgets/lv_image.h"],
  imagebutton: ["widgets/lv_imagebutton.h"],
  keyboard: ["widgets/lv_keyboard.h"],
  label: ["widgets/lv_label.h"],
  led: ["widgets/lv_led.h"],
  line: ["widgets/lv_line.h"],
  list: ["widgets/lv_list.h"],
  menu: ["widgets/lv_menu.h"],
  msgbox: ["widgets/lv_msgbox.h"],
  qrcode: ["widgets/lv_qrcode.h"],
  roller: ["widgets/lv_roller.h"],
  scale: ["widgets/lv_scale.h"],
  slider: ["widgets/lv_slider.h"],
  span: ["widgets/lv_span.h"],
  spinbox: ["widgets/lv_spinbox.h"],
  spinner: ["widgets/lv_spinner.h"],
  switch: ["widgets/lv_switch.h"],
  table: ["widgets/lv_table.h"],
  tabview: ["widgets/lv_tabview.h"],
  textarea: ["widgets/lv_textarea.h"],
  tileview: ["widgets/lv_tileview.h"],
  win: ["widgets/lv_win.h"],
};

function firstSentence(comment) {
  const lines = comment
    .replace(/^\/\*\*|\*\/$/g, "")
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, "").trim());
  const firstTag = lines.findIndex((l) => l.startsWith("@"));
  const text = (firstTag >= 0 ? lines.slice(0, firstTag) : lines).filter(Boolean).join(" ");
  const m = /^(.*?[.!?])(\s|$)/.exec(text);
  return (m ? m[1] : text).replace(/\s+/g, " ").slice(0, 160);
}

function parseHeader(file) {
  const src = readFileSync(file, "utf-8");
  const functions = [];
  const enums = [];
  // Enums: typedef enum { A, B } name_t;
  for (const m of src.matchAll(/typedef\s+enum\s*\{([^}]*)\}\s*(\w+)\s*;/g)) {
    const values = [...m[1].matchAll(/^\s*(LV_[A-Z0-9_]+)/gm)].map((v) => v[1]).filter((v) => !v.endsWith("_LAST"));
    if (values.length) enums.push({ name: m[2], values });
  }
  // Prototypes with their preceding doc comment (skip bodies of static inline functions).
  const re = /(\/\*\*(?:(?!\*\/)[\s\S])*\*\/)\s*((?:LV_DEPRECATED\([^)]*\)\s*)?)((?:[\w*]+\s+)+\**\s*(lv_\w+)\s*\(([^;{]*?)\))\s*;/g;
  for (const m of src.matchAll(re)) {
    const proto = m[3].replace(/\s+LV_FORMAT_ATTRIBUTE\([^)]*\)/, "").replace(/\s+/g, " ").replace(/\( /g, "(").replace(/ \)/g, ")").trim();
    if (/^(static|typedef)\b/.test(proto)) continue;
    const deprecated = !!m[2] || /@deprecated/.test(m[1]);
    functions.push({ proto: proto + ";", brief: firstSentence(m[1]), ...(deprecated ? { deprecated: true } : {}) });
  }
  return { functions, enums };
}

const table = [];
for (const [name, headers] of Object.entries(WIDGETS)) {
  const entry = { name, headers: headers.map((h) => `lvgl/${h}`), functions: [], enums: [] };
  for (const h of headers) {
    const file = path.join(inc, h);
    if (!existsSync(file)) {
      console.error(`warning: ${file} missing`);
      continue;
    }
    const { functions, enums } = parseHeader(file);
    entry.functions.push(...functions);
    entry.enums.push(...enums);
  }
  table.push(entry);
}

const version = /LVGL_VERSION_MAJOR\s+(\d+)[\s\S]*?LVGL_VERSION_MINOR\s+(\d+)[\s\S]*?LVGL_VERSION_PATCH\s+(\d+)/.exec(
  readFileSync(path.join(inc, "lv_version.h"), "utf-8")
);
const out = `// GENERATED by scripts/gen-widget-table.mjs from the LVGL ${version ? version.slice(1).join(".") : ""} public headers - do not edit.
import type { WidgetTableEntry } from "./widgets.js";

export const LVGL_HEADERS_VERSION = ${JSON.stringify(version ? version.slice(1).join(".") : "unknown")};

export const WIDGET_TABLE: WidgetTableEntry[] = ${JSON.stringify(table, null, 1)};
`;
const target = path.join(packageDir, "src", "resources", "docs", "widgets.generated.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${table.length} widgets, ${table.reduce((s, w) => s + w.functions.length, 0)} functions`);
